  Object.assign(MAPS, HERO_MAPS);
  const cache = {};
  function bake(type, lv, frame) {
    frame = frame || 0;
    const key = `${type}-${lv}-${frame}`;
    if (cache[key]) return cache[key];
    const map = HERO_MAPS[type] ? heroFrame(HERO_MAPS[type], frame) : FAM_MAPS[type] ? FAM_MAPS[type][frame === 1 ? 1 : 0] : ((frame === 1 && FRAMES2[type]) || MAPS[type]);
    const P = PAL[type] || PAL.monster;
    const pal = P[Math.min(P.length, lv) - 1];
    const c = document.createElement('canvas');
    c.width = 16; c.height = 16;
    const g = c.getContext('2d');
    for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
      const ch = map[y][x];
      if (ch === '.') continue;
      const col = ch === 'a' ? pal[0] : ch === 'b' ? pal[1] : ch === 'c' ? pal[2] : FIXED[ch];
      g.fillStyle = col; g.fillRect(x, y, 1, 1);
    }
    cache[key] = c;
    return c;
  }

  // 타일 → 스프라이트. frame 은 호출자가 시간으로 결정.
  function get(tile, frame) {
    if (tile.type === 'rune') return bake('rune_' + tile.rune, 1, 0);
    if (tile.type === 'monster' && tile.fam && tile.fam !== 'slime' && FAM_MAPS[tile.fam]) return bake(tile.fam, tile.lv || 1, frame || 0);
    return bake(tile.type, tile.lv || 1, frame || 0);
  }
  function hasFrames(type) { return !!FRAMES2[type] || !!HERO_MAPS[type] || !!FAM_MAPS[type]; }
  function famSprite(fam, lv, frame) { return fam && fam !== 'slime' && FAM_MAPS[fam] ? bake(fam, lv, frame || 0) : bake('monster', lv, frame || 0); }
  function hero(id, frame) { return bake('hero_' + id, 1, frame || 0); }

  MD.sprites = { get, bake, hero, famSprite, hasFrames, PAL };
